// Shift helper function: shifts any coordinate set by deltaLat and deltaLng
export function shiftCoords(coords: [number, number][], deltaLat: number, deltaLng: number): [number, number][] {
  return coords.map(([lat, lng]) => [lat + deltaLat, lng + deltaLng]);
}

// Full geometry resolver for any given case
export function getGeometryForCase(caseId: string) {
  const targetCase = demoCases.find((c) => c.id === caseId) || demoCases[0];
  const baseCenter: [number, number] = [28.375, -89.15];
  const deltaLat = targetCase.center[0] - baseCenter[0];
  const deltaLng = targetCase.center[1] - baseCenter[1];

  const spillPolygon = shiftCoords(baseSpillPolygon, deltaLat, deltaLng);
  const originPolygon = shiftCoords(baseOriginPolygon, deltaLat, deltaLng);
  const originCenter: [number, number] = [28.495 + deltaLat, -89.43 + deltaLng];

  const uncertaintyEllipses = baseUncertaintyEllipses.map((e) => ({
    ...e,
    center: [e.center[0] + deltaLat, e.center[1] + deltaLng] as [number, number],
  }));

  const isoRings = baseIsoRings.map((ring) => ({
    ...ring,
    points: shiftCoords(ring.points, deltaLat, deltaLng),
  }));

  const particles = baseParticles.map((p) => ({
    id: p.id,
    positions: p.positions.map((pos) => ({
      timeH: pos.timeH,
      lat: pos.lat + deltaLat,
      lng: pos.lng + deltaLng,
    })),
  }));

  const candidates = demoCandidates.map((candidate) => ({
    ...candidate,
    track: candidate.track.map((point) => ({
      ...point,
      lat: point.lat + deltaLat,
      lng: point.lng + deltaLng,
    })),
  }));

  return {
    targetCase,
    spillPolygon,
    originPolygon,
    originCenter,
    uncertaintyEllipses,
    isoRings,
    particles,
    candidates,
    center: targetCase.center,
  };
}

